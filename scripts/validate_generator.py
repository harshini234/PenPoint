from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from brd import params as P

D = ROOT / "data" / "demo"


def pct(x, d=1):
    return f"{100 * x:.{d}f}%"


def main() -> None:
    t = pd.read_csv(D / "truth_history.csv")
    obs = pd.read_csv(D / "lots_history.csv")
    cut = P.get("high_risk_cutoff")
    hi = t["morbidity_45"] >= cut
    call = t["buyer_risk_call"] == "high"
    cf = t["high_counterfactual"]

    rows = [
        ("Lots with >=15% morbidity (targeted)", P.get("target_prev_high_lots"), hi.mean(), "Rojas 2022 p2"),
        ("Mean 45-d morbidity (targeted)", P.get("target_mean_morbidity"), t["morbidity_45"].mean(), "Rojas 2022 p2"),
        ("Human-call sensitivity (targeted)", P.get("human_sensitivity"), (call & cf).sum() / cf.sum(), "Rojas 2022 p3"),
        ("Human-call specificity (targeted)", P.get("human_specificity"), (~call & ~cf).sum() / (~cf).sum(), "Rojas 2022 p3"),
        ("Mean morbidity, high lots (NOT targeted)", P.get("target_mean_morbidity_high"), t.loc[hi, "morbidity_45"].mean(), "Rojas 2022 p2"),
        ("Mean morbidity, low lots (NOT targeted)", P.get("target_mean_morbidity_low"), t.loc[~hi, "morbidity_45"].mean(), "Rojas 2022 p2"),
        ("Fall (Sep-Nov) 45-d incidence, cases/head (targeted)", P.get("target_fall_incidence"),
         (lambda f: f["cases_45"].sum() / f["head_count"].sum())(t[pd.to_datetime(t["arrival_date"]).dt.month.isin([9, 10, 11])]),
         "Cernicchiaro 2011 abstract"),
        ("Mean lot size, head", P.get("target_mean_lot_size"), t["head_count"].mean(), "Rojas 2022 Table 3"),
    ]
    lines = ["# Generator validation", "",
             "Generated by `scripts/validate_generator.py` on the demo history "
             f"({len(t):,} fictional lots, {t['head_count'].sum():,} head). All data are synthetic.", "",
             "## Does the generator reproduce the published figures?", "",
             "| Check | Published | Generated | Source |", "|---|---|---|---|"]
    for name, pub, gen, src in rows:
        f = (lambda v: f"{v:.0f}") if "size" in name else pct
        lines.append(f"| {name} | {f(pub)} | {f(gen)} | {src} |")
    lines += ["",
              "Targeted figures were fitted by `scripts/calibrate.py`; untargeted ones are an independent check of the "
              "shape of the risk distribution. Human sensitivity/specificity are computed against the counterfactual "
              "outcome without metaphylaxis (the generator knows it; Rojas could not - see their p6 limitation).", "",
              "## Sanity checks", "",
              f"- 45-day BRD mortality (mean of lots): {pct(t['mortality_45'].mean(), 2)}. Whole-feeding-period, all-cause "
              f"steer death loss in Kansas was 1.74% in 2017 (Front Vet Sci 2023), so a 45-day BRD-only figure should sit below it.",
              f"- High-risk tail: light (<550 lb), unpreconditioned sale-barn lots would average "
              f"{pct(t.loc[(t.market_channel == 'sale_barn') & (t.arrival_weight_lb < 550) & (t.preconditioning == 'none'), 'p_case_no_meta'].mean())} "
              "morbidity without metaphylaxis; research herds of high-risk calves report 48% (Wottlin 2021) and 51.5% (Pillen 2016), "
              "so our extreme tail is likely conservative.",
              f"- Lots given metaphylaxis under current practice: {pct(t['metaphylaxis_given'].mean())} "
              "(context only: NAHMS 2017 p4 reports the share of *feedlots*, not lots - 39.3% of large feedlots group-treat "
              "some arriving cattle - so the two are not directly comparable).", "",
              "## Operating differences between yards (current practice)", "",
              "| Yard | Lots | Mean arrival wt (lb) | Sale-barn share | Mean morbidity | Lots >=15% | Metaphylaxis rate |",
              "|---|---|---|---|---|---|---|"]
    for y, g in t.groupby("yard_id"):
        lines.append(f"| {y} | {len(g)} | {g['arrival_weight_lb'].mean():.0f} | {pct((g['market_channel'] == 'sale_barn').mean(), 0)} | "
                     f"{pct(g['morbidity_45'].mean())} | {pct((g['morbidity_45'] >= cut).mean())} | {pct(g['metaphylaxis_given'].mean(), 0)} |")
    lines += ["", "## Missing information (what the manager sees)", "",
              "| Channel | Lots | haul_hours | n_sources | preconditioning | origin_state | pay_weight_lb |", "|---|---|---|---|---|---|---|"]
    for ch, g in obs.groupby("market_channel"):
        lines.append(f"| {ch} | {len(g)} | " + " | ".join(pct(g[c].isna().mean(), 0) for c in
                     ["haul_hours", "n_sources", "preconditioning", "origin_state", "pay_weight_lb"]) + " |")
    lines += ["", "Missingness is deliberately concentrated in sale-barn lots, which are also the riskiest "
              "(an assumption, tagged in params/parameters.yaml as `missing_rates`)."]
    out = ROOT / "docs" / "generator_validation.md"
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
